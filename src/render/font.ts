export interface StrokeSeg { x0: number; y0: number; x1: number; y1: number }

/** Generates world-aligned (before rotation/mirror) line segments for `text` centered at (0,0). */
export function textStrokes(text: string, size: number): StrokeSeg[] {
  const s = text.toUpperCase();
  const cw = size * 0.62;
  const gap = size * 0.22;
  const totalW = s.length > 0 ? s.length * cw + (s.length - 1) * gap : 0;
  const xStart = -totalW / 2;
  const yStart = -size * 0.5;
  const segs: StrokeSeg[] = [];

  for (let i = 0; i < s.length; i++) {
    const ch = s[i];
    const polys = G[ch];
    if (!polys) continue;
    const ox = xStart + i * (cw + gap);
    for (const p of polys) {
      for (let k = 0; k + 3 < p.length; k += 2) {
        segs.push({
          x0: ox + p[k] * cw,
          y0: yStart + p[k + 1] * size,
          x1: ox + p[k + 2] * cw,
          y1: yStart + p[k + 3] * size,
        });
      }
    }
  }
  return segs;
}
