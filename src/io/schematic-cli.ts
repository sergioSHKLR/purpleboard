// Builds a SPICE part library from a schematic PDF + boardview.
//
//   npm run schematic -- <schematic.pdf | bom.csv> <board.brd> [--product 639-00623] [-o lib.json] [--list] [--report]
//
// Default output: "<board>.spice.json" next to the boardview, which `npm run spice` loads
// automatically for that board.
import { PdfDocument } from './pdf';
import { extractSchematic } from './schematic';
import { schematicToLibrary } from './schematicLibrary';
import { parseBrd } from './brd';
import { parseBomCsv } from './bom';

interface Fs { readFileSync(p: string): Uint8Array; writeFileSync(p: string, d: string): void }
interface Zlib { inflateSync(d: Uint8Array): Uint8Array }
interface Proc { argv: string[]; exitCode?: number; stdout: { write(s: string): void } }
const proc = (globalThis as unknown as { process: Proc }).process;
const out = (s: string) => proc.stdout.write(s + '\n');

async function main() {
  const fs = (await import(/* @vite-ignore */ 'node:' + 'fs')) as Fs;
  const zlib = (await import(/* @vite-ignore */ 'node:' + 'zlib')) as Zlib;
  const args = proc.argv.slice(2);
  const take = (k: string) => { const i = args.indexOf(k); if (i < 0) return undefined; const v = args[i + 1]; args.splice(i, 2); return v; };
  const flag = (k: string) => { const i = args.indexOf(k); if (i < 0) return false; args.splice(i, 1); return true; };
  const product = take('--product');
  const outFile = take('-o') ?? take('--out');
  const list = flag('--list');
  const showReport = flag('--report');
  const [pdfPath, brdPath] = args;
  if (!pdfPath || !brdPath) {
    out('usage: npm run schematic -- <schematic.pdf> <board.brd> [--product <639-…>] [-o lib.json] [--list] [--report]');
    proc.exitCode = 2;
    return;
  }

  const t0 = performance.now();
  const brd = parseBrd(new Uint8Array(fs.readFileSync(brdPath)), brdPath);
  const comps = brd.board.components.filter((c) => !(c.ref.startsWith('J_') && c.kind === 'battery'));
  const nets = new Set(comps.flatMap((c) => c.pads.map((p) => p.net).filter((n): n is string => !!n)));
  let sch;
  if (/\.(csv|tsv|txt)$/i.test(pdfPath)) {
    sch = parseBomCsv(new TextDecoder().decode(fs.readFileSync(pdfPath)));
    out(`parsed BOM: ${sch.parts.size} designators, ${comps.length} boardview parts in ${(performance.now() - t0).toFixed(0)} ms`);
  } else {
    const pages = new PdfDocument(new Uint8Array(fs.readFileSync(pdfPath)), (d) => new Uint8Array(zlib.inflateSync(d))).pages();
    sch = extractSchematic(pages, { refs: comps.map((c) => c.ref), nets });
    out(`parsed ${pages.length} sheets, ${comps.length} boardview parts in ${(performance.now() - t0).toFixed(0)} ms`);
  }

  if (list || !sch.bom.products.length) {
    out(`BOM configurations (${sch.bom.products.length}):`);
    for (const p of sch.bom.products) out(`  ${p.partNumber}  ${p.description}`);
    if (list) return;
  }
  const chosen = product ?? sch.bom.products[0]?.partNumber ?? null;
  if (product && !sch.bom.products.some((p) => p.partNumber === product)) {
    out(`error: unknown product ${product} (use --list)`);
    proc.exitCode = 1;
    return;
  }
  const lib = schematicToLibrary(sch, comps, chosen);
  const counts: Record<string, number> = {};
  for (const r of lib.report) counts[r.source] = (counts[r.source] ?? 0) + 1;
  out(`BOM configuration: ${chosen ?? '(none)'}${chosen ? ' — ' + sch.bom.products.find((p) => p.partNumber === chosen)?.description : ''}`);
  out(`parts: ${Object.entries(counts).map(([k, v]) => `${k}=${v}`).join(', ')}`);
  const dc = lib.devices.convention;
  out(`two-pin diode footprints: pad 1 = ${dc.pad1 === 'A' ? 'anode' : 'cathode'} (votes A=${dc.votesAnode} K=${dc.votesCathode}${dc.conflicts.length ? `, conflicts: ${dc.conflicts.join(' ')}` : ''})`);
  const dstat: Record<string, number> = {};
  for (const d of lib.devices.report) dstat[d.status] = (dstat[d.status] ?? 0) + 1;
  out(`devices: ${Object.entries(dstat).map(([k, v]) => `${k}=${v}`).join(', ')}`);
  for (const d of lib.devices.report.filter((x) => x.status === 'rejected')) out(`  rejected ${d.ref}: ${d.detail}`);
  if (showReport) for (const r of lib.report) out(`  ${r.ref}\t${r.source}\t${r.spec ?? ''}\t${r.detail}`);

  const file = outFile ?? brdPath.replace(/\.[^.\\/]+$/, '') + '.spice.json';
  const doc = {
    _comment: 'Generated by `npm run schematic` from the board schematic. Derived from proprietary documentation: keep private, do not redistribute.',
    source: { schematic: pdfPath.replace(/^.*[\\/]/, ''), boardview: brdPath.replace(/^.*[\\/]/, ''), product: chosen },
    summary: counts,
    ...lib.library,
    partNumbers: lib.partNumbers,
    ratings: lib.ratings,
    bomOptions: lib.options,
    diodeConvention: lib.devices.convention,
    devices: lib.devices.report,
    unresolved: lib.report.filter((r) => r.source === 'unresolved').map((r) => `${r.ref}: ${r.detail}`),
  };
  fs.writeFileSync(file, JSON.stringify(doc, null, 1));
  out(`wrote ${file}`);
}

main().catch((e: unknown) => { out(`error: ${e instanceof Error ? e.stack ?? e.message : String(e)}`); proc.exitCode = 1; });
